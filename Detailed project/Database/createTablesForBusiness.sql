USE Db_QuyChe_Business;
GO

-- 1. Bảng TAI_LIEU
CREATE TABLE TAI_LIEU (
    MaTaiLieu VARCHAR(20) PRIMARY KEY,
    TieuDe NVARCHAR(255) NOT NULL,
    LoaiVanBan VARCHAR(50) NOT NULL, -- PDF, Word, HTML
    LinhVuc NVARCHAR(100), -- Đất đai, Nhà ở, Quy hoạch
    CoQuanBanHanh NVARCHAR(150),
    NgayTao DATETIME DEFAULT GETDATE()
);

-- 2. Bảng NGUOI_DUNG
CREATE TABLE NGUOI_DUNG (
    MaND VARCHAR(20) PRIMARY KEY,
    TenDangNhap VARCHAR(50) UNIQUE NOT NULL,
    MatKhauHash VARCHAR(255) NOT NULL,
    HoTen NVARCHAR(100),
    Email VARCHAR(100),
    VaiTro VARCHAR(50) -- ChuyenVienPhapChe, QuanTriVien, NguoiDung
);

-- 3. Bảng PHIEN_BAN_TAI_LIEU
CREATE TABLE PHIEN_BAN_TAI_LIEU (
    MaPhienBan VARCHAR(20) PRIMARY KEY,
    MaTaiLieu VARCHAR(20) FOREIGN KEY REFERENCES TAI_LIEU(MaTaiLieu),
    MaND VARCHAR(20) FOREIGN KEY REFERENCES NGUOI_DUNG(MaND),
    SoPhienBan VARCHAR(50) NOT NULL,
    NgayHieuLuc DATETIME,
    NgayHetHieuLuc DATETIME,
    TrangThai NVARCHAR(50) DEFAULT 'Draft', -- Draft, Approved, Expired
    DuongDanFile NVARCHAR(500),
    is_active BIT DEFAULT 0 -- 1 = Đang hiệu lực, 0 = Hết hiệu lực
);

-- 4. Bảng DOAN_VAN_BAN (Chunks)
CREATE TABLE DOAN_VAN_BAN (
    MaDoan VARCHAR(20) PRIMARY KEY,
    MaPhienBan VARCHAR(20) FOREIGN KEY REFERENCES PHIEN_BAN_TAI_LIEU(MaPhienBan),
    ThuTu INT,
    DieuKhoan NVARCHAR(100),
    NoiDung NVARCHAR(MAX) NOT NULL,
    SoTrang INT
);

-- 5. Bảng PHIEN_HOI_DAP
CREATE TABLE PHIEN_HOI_DAP (
    MaPhien VARCHAR(20) PRIMARY KEY,
    MaND VARCHAR(20) FOREIGN KEY REFERENCES NGUOI_DUNG(MaND),
    ThoiGianBatDau DATETIME DEFAULT GETDATE(),
    ThoiGianKetThuc DATETIME
);

-- 6. Bảng CAU_HOI
CREATE TABLE CAU_HOI (
    MaCauHoi VARCHAR(20) PRIMARY KEY,
    MaPhien VARCHAR(20) FOREIGN KEY REFERENCES PHIEN_HOI_DAP(MaPhien),
    NoiDung TEXT NOT NULL,
    ThoiDiem DATETIME DEFAULT GETDATE()
);

-- 7. Bảng CAU_TRA_LOI
CREATE TABLE CAU_TRA_LOI (
    MaCauTraLoi VARCHAR(20) PRIMARY KEY,
    MaCauHoi VARCHAR(20) FOREIGN KEY REFERENCES CAU_HOI(MaCauHoi),
    NoiDung NVARCHAR(MAX),
    TrangThai NVARCHAR(50), -- ThanhCong, TuChoi
    DoTinCay FLOAT,
    LyDoTuChoi NVARCHAR(255),
    TraceId VARCHAR(100) -- OpenTelemetry Audit ID
);

-- 8. Bảng TRICH_DAN
CREATE TABLE TRICH_DAN (
    MaTrichDan INT IDENTITY(1,1) PRIMARY KEY,
    MaCauTraLoi VARCHAR(20) FOREIGN KEY REFERENCES CAU_TRA_LOI(MaCauTraLoi),
    MaDoan VARCHAR(20) FOREIGN KEY REFERENCES DOAN_VAN_BAN(MaDoan),
    ThuTu INT,
    DoanTrich NVARCHAR(MAX)
);

-- 9. Bảng CHI_TIET_TRUY_XUAT
CREATE TABLE CHI_TIET_TRUY_XUAT (
    MaCauHoi VARCHAR(20) FOREIGN KEY REFERENCES CAU_HOI(MaCauHoi),
    MaDoan VARCHAR(20) FOREIGN KEY REFERENCES DOAN_VAN_BAN(MaDoan),
    ThuHang INT,
    DiemTuongDong FLOAT,
    PRIMARY KEY (MaCauHoi, MaDoan)
);

-- 10. Bảng PHAN_HOI
CREATE TABLE PHAN_HOI (
    MaPhanHoi VARCHAR(20) PRIMARY KEY,
    MaCauTraLoi VARCHAR(20) FOREIGN KEY REFERENCES CAU_TRA_LOI(MaCauTraLoi),
    MaND VARCHAR(20) FOREIGN KEY REFERENCES NGUOI_DUNG(MaND),
    DanhGia NVARCHAR(20), -- Like, Dislike
    GhiChu NVARCHAR(MAX)
);

-- 11. Bảng BO_DANH_GIA
CREATE TABLE BO_DANH_GIA (
    MaBo VARCHAR(20) PRIMARY KEY,
    TenBo NVARCHAR(255) NOT NULL,
    NgayTao DATETIME DEFAULT GETDATE()
);

-- 12. Bảng CAU_HOI_DANH_GIA
CREATE TABLE CAU_HOI_DANH_GIA (
    MaCauHoiDG VARCHAR(20) PRIMARY KEY,
    MaBo VARCHAR(20) FOREIGN KEY REFERENCES BO_DANH_GIA(MaBo),
    MaDoanChuan VARCHAR(20) FOREIGN KEY REFERENCES DOAN_VAN_BAN(MaDoan),
    LoaiCau NVARCHAR(50), -- DungPhamVi, NgoaiPhamVi
    DapAnChuan NVARCHAR(MAX)
);

-- 13. Bảng KET_QUA_DANH_GIA
CREATE TABLE KET_QUA_DANH_GIA (
    MaKQ VARCHAR(20) PRIMARY KEY,
    MaBo VARCHAR(20) FOREIGN KEY REFERENCES BO_DANH_GIA(MaBo),
    NgayChay DATETIME DEFAULT GETDATE(),
    TyLeDung FLOAT,
    TyLeTuChoiDung FLOAT,
    TyLeTrichDanDung FLOAT
);

-- 14. Bảng CHI_TIET_KET_QUA
CREATE TABLE CHI_TIET_KET_QUA (
    MaKQ VARCHAR(20) FOREIGN KEY REFERENCES KET_QUA_DANH_GIA(MaKQ),
    MaCauHoiDG VARCHAR(20) FOREIGN KEY REFERENCES CAU_HOI_DANH_GIA(MaCauHoiDG),
    KetQuaDung BIT,
    TrichDanDung BIT,
    PRIMARY KEY (MaKQ, MaCauHoiDG)
);

GO